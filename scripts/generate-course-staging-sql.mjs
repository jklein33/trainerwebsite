import { readFile, writeFile } from "node:fs/promises";

// Keep the local and staging definitions in sync. This script writes files only;
// it never connects to a database. Review and run the generated SQL separately.
const root = new URL("../", import.meta.url);
const read = (path) => readFile(new URL(path, root), "utf8");
const scope = (sql) =>
  sql
    .replaceAll("public.", "course_staging.")
    .replaceAll("'public'", "'course_staging'")
    .replaceAll("course-media", "course-staging-media")
    .replaceAll("course_profile_signup", "course_staging_profile_signup")
    .replaceAll("course_storage_admin", "course_staging_storage_admin");

const preamble = `-- Client staging installation. Run once, BEFORE registering any accounts.
-- Generated by scripts/generate-course-staging-sql.mjs; do not edit this copy.
-- Existing public tables are preserved. This is not an upgrade or a DB reset.
begin;

-- Fail closed if the audited Auth/Storage state has changed. Review it first.
do $$ begin
  if exists(select 1 from auth.users)
    or exists(select 1 from pg_trigger where tgrelid='auth.users'::regclass and not tgisinternal)
    or exists(select 1 from pg_policies where schemaname='storage' and tablename='objects')
    or exists(select 1 from storage.buckets where id='course-staging-media') then
    raise exception 'Auth or Storage differs from the empty audited state. Stop and review before installing.';
  end if;
end $$;
create schema course_staging;
revoke all on schema course_staging from public,anon,authenticated;
grant usage on schema course_staging to authenticated,service_role;
`;

let install = scope(
  await read("supabase/migrations/202609080001_course_platform.sql"),
);
install = preamble + install.slice(install.indexOf("begin;") + "begin;".length);
install = install.replace(
  /^insert into course_staging\.course_profiles\(id,email\).*$/m,
  "-- No existing Auth accounts are imported by this initial installation.",
);
install = install.replace("on conflict(id) do update set public=false;", ";");
install = install.replace(
  "\ncommit;",
  `
-- Avoid inheriting broad global default privileges on new sequences.
revoke all on all sequences in schema course_staging from public,anon,authenticated;
grant usage,select on sequence course_staging.course_audit_log_id_seq to service_role;
notify pgrst, 'reload schema';
commit;`,
);

const outputs = {
  "01-install-course-staging.sql": install,
  "02-verify-course-staging.sql": scope(
    await read("supabase/sql-editor/02-verify-course-platform.sql"),
  ),
  "03-promote-course-staging-admin.sql": scope(
    await read("supabase/sql-editor/03-promote-course-admin.sql"),
  ),
};
for (const [name, sql] of Object.entries(outputs)) {
  await writeFile(new URL(`supabase/sql-editor/${name}`, root), sql);
}
console.log(
  "Generated staging install, verification and administrator SQL. No database was accessed.",
);
